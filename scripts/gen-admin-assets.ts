// Embeds the admin UI's static assets (packages/admin-ui/assets) into packages/admin-ui/src/assets.generated.ts (P4-03):
// Workers can't read files at runtime, and one bundle serves `serve` and the Worker alike. Each asset gets a content
// hash in its published name (cached `immutable`) and a SHA-384 Subresource Integrity value for its tag.
// Run: `pnpm ui:assets` or `node scripts/gen-admin-assets.ts --check` (part of `pnpm lint`).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DIR = fileURLToPath(new URL('../packages/admin-ui/assets/', import.meta.url));
const OUT = fileURLToPath(new URL('../packages/admin-ui/src/assets.generated.ts', import.meta.url));

/** Source files, by key. Only these are published. */
export const SOURCES: Readonly<Record<string, { file: string; type: string }>> = {
  css: { file: 'admin.css', type: 'text/css; charset=utf-8' },
  js: { file: 'admin.js', type: 'text/javascript; charset=utf-8' },
};

export interface BuiltAsset {
  readonly file: string;
  readonly type: string;
  readonly integrity: string;
  readonly body: string;
}

export function buildAsset(file: string, type: string, body: string): BuiltAsset {
  const hash = createHash('sha256').update(body).digest('hex').slice(0, 16);
  const dot = file.lastIndexOf('.');
  const integrity = `sha384-${createHash('sha384').update(body).digest('base64')}`;
  return { file: `${file.slice(0, dot)}.${hash}${file.slice(dot)}`, type, integrity, body };
}

export function renderModule(assets: Readonly<Record<string, BuiltAsset>>): string {
  return [
    '// SPDX-License-Identifier: Apache-2.0',
    '// GENERATED by scripts/gen-admin-assets.ts from packages/admin-ui/assets — do not edit.',
    "import type { StaticAsset } from './assets.ts';",
    '',
    `export const GENERATED_ASSETS: Readonly<Record<'css' | 'js', StaticAsset>> = Object.freeze(${JSON.stringify(assets, null, 2)});`,
    '',
  ].join('\n');
}

export function main(args: string[]): number {
  const built: Record<string, BuiltAsset> = {};
  for (const [key, { file, type }] of Object.entries(SOURCES)) {
    built[key] = buildAsset(file, type, readFileSync(`${DIR}${file}`, 'utf8'));
  }
  const next = renderModule(built);
  if (args.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      // missing counts as stale
    }
    if (current !== next) {
      console.error('✗ packages/admin-ui/src/assets.generated.ts is stale — run `pnpm ui:assets`');
      return 1;
    }
    console.log('✓ embedded admin UI assets are up to date');
    return 0;
  }
  writeFileSync(OUT, next);
  console.log('Updated packages/admin-ui/src/assets.generated.ts');
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
