// Builds the MCP Apps chart view (P7-04) from packages/core/assets/chart-app.{html,css,js} into one self-contained
// HTML string in packages/core/src/apps/chart-app.generated.ts: Workers can't read files at runtime, and one bundle
// serves stdio, `serve` and the Worker alike.
// Run: `node scripts/gen-app-assets.ts` or `node scripts/gen-app-assets.ts --check` (part of `pnpm lint`).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DIR = fileURLToPath(new URL('../packages/core/assets/', import.meta.url));
const OUT = fileURLToPath(new URL('../packages/core/src/apps/chart-app.generated.ts', import.meta.url));

const STYLE_SLOT = '/*@STYLE@*/';
const SCRIPT_SLOT = '/*@SCRIPT@*/';

/** Inline the style and script into the page. Refuses anything that could end the inline block early. */
export function buildPage(html: string, css: string, js: string): string {
  if (!html.includes(STYLE_SLOT) || !html.includes(SCRIPT_SLOT))
    throw new Error('chart-app.html lost a slot');
  if (/<\/style|<!--/i.test(css)) throw new Error('chart-app.css must not contain </style or <!--');
  if (/<\/script|<!--|<script/i.test(js))
    throw new Error('chart-app.js must not contain <script, </script or <!--');
  // Function replacers: `$` sequences in the sources are kept as they are.
  return html.replace(STYLE_SLOT, () => css.trim()).replace(SCRIPT_SLOT, () => js.trim());
}

export function renderModule(page: string): string {
  return [
    '// SPDX-License-Identifier: Apache-2.0',
    '// GENERATED by scripts/gen-app-assets.ts from packages/core/assets/chart-app.* — do not edit.',
    '',
    '/** The MCP Apps chart view (P7-04): one self-contained HTML page. */',
    `export const CHART_APP_HTML: string = ${JSON.stringify(page)};`,
    '',
  ].join('\n');
}

export function main(args: string[]): number {
  const read = (f: string) => readFileSync(`${DIR}${f}`, 'utf8');
  const next = renderModule(buildPage(read('chart-app.html'), read('chart-app.css'), read('chart-app.js')));
  if (args.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      // missing counts as stale
    }
    if (current !== next) {
      console.error('✗ packages/core/src/apps/chart-app.generated.ts is stale — run `pnpm app:assets`');
      return 1;
    }
    console.log('✓ embedded MCP Apps chart view is up to date');
    return 0;
  }
  writeFileSync(OUT, next);
  console.log('Updated packages/core/src/apps/chart-app.generated.ts');
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
