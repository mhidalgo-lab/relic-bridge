// Embeds the drizzle-kit SQL migrations (packages/storage/migrations) into
// packages/storage/src/migrations.generated.ts, because Workers can't read files at runtime (P2-01).
// Run: `pnpm db:generate` (drizzle-kit + this) or `node scripts/gen-migrations.ts --check` (part of `pnpm lint`).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DIR = fileURLToPath(new URL('../packages/storage/migrations/', import.meta.url));
const OUT = fileURLToPath(new URL('../packages/storage/src/migrations.generated.ts', import.meta.url));

export interface JournalEntry {
  idx: number;
  tag: string;
}

export interface EmbeddedMigration {
  version: number;
  name: string;
  checksum: string;
  statements: string[];
}

/** drizzle-kit separates statements with `--> statement-breakpoint`. */
export function splitStatements(sql: string): string[] {
  return sql
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

export function buildMigrations(
  journal: readonly JournalEntry[],
  read: (tag: string) => string,
): EmbeddedMigration[] {
  const sorted = [...journal].sort((a, b) => a.idx - b.idx);
  return sorted.map((entry, i) => {
    if (entry.idx !== i) throw new Error(`migration journal is not contiguous at ${entry.tag}`);
    const statements = splitStatements(read(entry.tag));
    if (statements.length === 0) throw new Error(`migration ${entry.tag} is empty`);
    const checksum = createHash('sha256').update(statements.join('\n;\n')).digest('hex');
    return { version: i + 1, name: entry.tag, checksum, statements };
  });
}

export function renderModule(migrations: readonly EmbeddedMigration[]): string {
  return [
    '// SPDX-License-Identifier: Apache-2.0',
    '// GENERATED by scripts/gen-migrations.ts from packages/storage/migrations — do not edit.',
    "import type { Migration } from './migrate.ts';",
    '',
    `export const MIGRATIONS: readonly Migration[] = Object.freeze(${JSON.stringify(migrations, null, 2)});`,
    '',
  ].join('\n');
}

export function main(args: string[]): number {
  const journal = (
    JSON.parse(readFileSync(`${DIR}meta/_journal.json`, 'utf8')) as { entries: JournalEntry[] }
  ).entries;
  const next = renderModule(buildMigrations(journal, (tag) => readFileSync(`${DIR}${tag}.sql`, 'utf8')));
  if (args.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      // missing counts as stale
    }
    if (current !== next) {
      console.error('✗ packages/storage/src/migrations.generated.ts is stale — run `pnpm db:generate`');
      return 1;
    }
    console.log('✓ embedded migrations are up to date');
    return 0;
  }
  writeFileSync(OUT, next);
  console.log('Updated packages/storage/src/migrations.generated.ts');
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
