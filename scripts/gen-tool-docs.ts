// Generates docs/reference/tools.md from the built-in tool registry (P1-13).
// Run: `pnpm docs:tools` (write) or `pnpm docs:tools --check` (fail when stale; part of `pnpm lint`).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  annotationsFor,
  createBuiltinTools,
  inputJsonSchema,
  outputJsonSchema,
  PROMPTS,
  type PromptDefinition,
  promptArgsJsonSchema,
  RESOURCES,
  type ResourceDefinition,
  type ToolDefinition,
} from '../packages/core/src/index.ts';

const RESOURCES_OUT = fileURLToPath(new URL('../docs/reference/resources.md', import.meta.url));
const PROMPTS_OUT = fileURLToPath(new URL('../docs/reference/prompts.md', import.meta.url));
const OUT = fileURLToPath(new URL('../docs/reference/tools.md', import.meta.url));

type Json = Record<string, unknown>;

/** Short type label for a JSON Schema node. */
export function typeLabel(node: unknown): string {
  if (node === null || typeof node !== 'object') return 'any';
  const s = node as Json;
  if (Array.isArray(s['enum'])) return (s['enum'] as unknown[]).map((v) => JSON.stringify(v)).join(' \\| ');
  if ('const' in s) return JSON.stringify(s['const']);
  for (const key of ['anyOf', 'oneOf']) {
    const alts = s[key];
    if (Array.isArray(alts)) return alts.map(typeLabel).join(' \\| ');
  }
  const t = s['type'];
  if (t === 'array') return `${typeLabel(s['items'])}[]`;
  if (Array.isArray(t)) return t.join(' \\| ');
  if (typeof t === 'string') return t;
  return 'any';
}

function cell(text: string): string {
  return text
    .replace(/\r?\n+/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();
}

/** Markdown table of the top-level properties of an object schema. */
export function renderFields(schema: Json): string {
  const props = (schema['properties'] ?? {}) as Record<string, Json>;
  const required = new Set((schema['required'] as string[] | undefined) ?? []);
  const names = Object.keys(props);
  if (names.length === 0) return '_No fields._\n';
  const rows = names.map((n) => {
    const p = props[n] as Json;
    const type = typeLabel(p).replace(/\\\|/g, '\\|');
    const desc = typeof p['description'] === 'string' ? cell(p['description']) : '';
    const def = 'default' in p ? ` Default: \`${JSON.stringify(p['default'])}\`.` : '';
    return `| \`${n}\` | \`${type}\` | ${required.has(n) ? 'yes' : 'no'} | ${desc}${def} |`;
  });
  return ['| Field | Type | Required | Description |', '| --- | --- | --- | --- |', ...rows, ''].join('\n');
}

function renderTool(def: ToolDefinition): string {
  const a = annotationsFor(def);
  const out = outputJsonSchema(def) as Json | undefined;
  const lines = [
    `## \`${def.name}\``,
    '',
    `**${def.title}** · group \`${def.group}\` · phase ${def.phase} · kind \`${def.kind}\` · cost ${def.cost} NerdGraph call${def.cost === 1 ? '' : 's'}`,
    '',
    def.description.trim(),
    '',
    '### Input',
    '',
    renderFields(inputJsonSchema(def)),
    '### Output',
    '',
    out ? renderFields(out) : '_Text only (no structured output)._\n',
    '### Annotations',
    '',
    `readOnly: \`${a.readOnlyHint}\` · destructive: \`${a.destructiveHint}\` · idempotent: \`${a.idempotentHint}\` · openWorld: \`${a.openWorldHint}\``,
    '',
  ];
  return lines.join('\n');
}

export function renderToolsDoc(tools: readonly ToolDefinition[]): string {
  const sorted = [...tools].sort((x, y) => x.group.localeCompare(y.group) || x.name.localeCompare(y.name));
  const index = [
    '| Tool | Group | Kind | Cost | Phase |',
    '| --- | --- | --- | --- | --- |',
    ...sorted.map((t) => `| [\`${t.name}\`](#${t.name}) | ${t.group} | ${t.kind} | ${t.cost} | ${t.phase} |`),
  ].join('\n');
  return [
    '<!-- Generated by `pnpm docs:tools` from the tool registry. Do not edit by hand. -->',
    '',
    '# Tool reference',
    '',
    `${sorted.length} tools. Cost is the expected number of NerdGraph calls per tool call (ADR-0010). Annotations are derived from the tool kind, never hand-written.`,
    '',
    index,
    '',
    ...sorted.map(renderTool),
  ]
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()
    .concat('\n');
}

function renderPrompts(prompts: readonly PromptDefinition[]): string {
  const sorted = [...prompts].sort((a, b) => a.name.localeCompare(b.name));
  const body = sorted.map((p) =>
    [
      `## \`${p.name}\``,
      '',
      `**${p.title}**. ${p.description}`,
      '',
      `Offered when the connection can use at least one of: ${p.needsAnyOf.map((t) => `\`${t}\``).join(', ')}.`,
      '',
      '### Arguments',
      '',
      renderFields(promptArgsJsonSchema(p)),
      '### Steps (tool, skipped when not allowed)',
      '',
      ...p.steps.map((s, i) => `${i + 1}. ${s.tool === undefined ? '(no tool)' : `\`${s.tool}\``}`),
      '',
    ].join('\n'),
  );
  return [
    '<!-- Generated by `pnpm docs:tools` from the prompt catalogue. Do not edit by hand. -->',
    '',
    '# Prompt reference',
    '',
    `${sorted.length} MCP prompts (investigation workflows). A prompt is text that tells the agent which tools to call; it reads no data. Prompts are listed per connection: one whose tools are all outside the grant is not listed, and a step naming a tool the connection can't use is left out. Argument values are quoted data, never instructions.`,
    '',
    ...body,
  ]
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()
    .concat('\n');
}

function renderResources(resources: readonly ResourceDefinition[]): string {
  const body = resources.map((r) =>
    [
      `## \`${r.uri}\``,
      '',
      `**${r.title}**. ${r.description}`,
      '',
      `- Kind: ${r.kind === 'static' ? 'static resource' : 'resource template'}; MIME type \`${r.mimeType}\``,
      `- Offered when the connection can use \`${r.needsTool}\`.`,
      r.kind === 'event_types'
        ? '- `resources/list` names one URI per account of the connection (and no other account).'
        : r.kind === 'attributes'
          ? '- Never listed: build the URI from an event type returned by the event-types resource.'
          : '- Original text bundled with the server; no New Relic call.',
      '',
    ].join('\n'),
  );
  return [
    '<!-- Generated by `pnpm docs:tools` from the resource catalogue. Do not edit by hand. -->',
    '',
    '# Resource reference',
    '',
    `${resources.length} MCP resources (\`resources/list\`, \`resources/templates/list\`, \`resources/read\`). URIs are stable. A resource is offered only when the tool behind it is in the connection's allowed list, otherwise its URI is unknown.`,
    '',
    'Schema resources are readers over `list_event_types` and `get_attributes`: the same account check (an account outside the connection is refused with `RB_AUTH_FORBIDDEN`, no New Relic call), event-type allow and deny lists, per-credential cache (5 minutes), request budget and audit row. The window is fixed at the last 24 hours. Names come from the account and are labelled as untrusted data. `{eventType}` is percent-encoded and case-sensitive.',
    '',
    ...body,
  ]
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()
    .concat('\n');
}

export function main(args: string[]): number {
  const targets = [
    { file: OUT, name: 'docs/reference/tools.md', next: renderToolsDoc(createBuiltinTools()) },
    { file: PROMPTS_OUT, name: 'docs/reference/prompts.md', next: renderPrompts(PROMPTS) },
    { file: RESOURCES_OUT, name: 'docs/reference/resources.md', next: renderResources(RESOURCES) },
  ];
  if (args.includes('--check')) {
    let stale = 0;
    for (const t of targets) {
      let current = '';
      try {
        current = readFileSync(t.file, 'utf8');
      } catch {
        // missing counts as stale
      }
      if (current !== t.next) {
        console.error(`✗ ${t.name} is stale — run \`pnpm docs:tools\``);
        stale += 1;
      } else console.log(`✓ ${t.name} is up to date`);
    }
    return stale === 0 ? 0 : 1;
  }
  for (const t of targets) {
    writeFileSync(t.file, t.next);
    console.log(`Updated ${t.name}`);
  }
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
